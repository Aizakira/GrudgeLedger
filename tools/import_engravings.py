"""Import ChatGPT's atlas of region engravings (owner, 24/11) into the addon.

Source: art/reference-journal/2026-11-24-atlas-gravures-regions (owner-local, not on GitHub).
Writes GrudgeLedger/Media/Engravings/<slug>.tga at 256 x 128 (shown at about 180 x 90: half the
weight of the 512 x 256 originals, no visible loss) and GrudgeLedger/EngravingData.lua, the lookup by
uiMapID and by normalized zone name (French and English aliases).
"""
from pathlib import Path
import json
import unicodedata
from PIL import Image

WORK = Path(__file__).resolve().parent.parent
LOT = WORK / "art" / "reference-journal" / "2026-11-24-atlas-gravures-regions"
OUT = WORK / "GrudgeLedger" / "Media" / "Engravings"


def normalize(name):
    text = unicodedata.normalize("NFKD", name)
    text = "".join(c for c in text if not unicodedata.combining(c)).lower()
    for mark in ("’", "'", "`", "-", "(", ")", ",", "."):
        text = text.replace(mark, " ")
    return " ".join(text.split())


def lua(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


manifest = json.loads((LOT / "manifest.json").read_text(encoding="utf-8"))
OUT.mkdir(parents=True, exist_ok=True)
maps, names = {}, {}
for asset in manifest["assets"]:
    slug = asset["slug"]
    image = Image.open(LOT / asset["png"]).convert("RGBA").resize((256, 128), Image.LANCZOS)
    for x in (0, 255):
        for y in (0, 127):
            image.putpixel((x, y), (0, 0, 0, 0))
    image.save(OUT / (slug + ".tga"), compression=None)
    if asset.get("uiMapID"):
        maps[int(asset["uiMapID"])] = slug
    for alias in [asset["name_fr"], asset["name_en"]] + list(asset.get("aliases", [])):
        names.setdefault(normalize(alias), slug)
        # "Gangrebois (Felwood)": each half alone as well.
        if "(" in alias:
            outer, inner = alias.split("(", 1)
            names.setdefault(normalize(outer), slug)
            names.setdefault(normalize(inner), slug)

lines = ["-- Generated by tools/import_engravings.py from ChatGPT's atlas of region engravings (24/11/2026).",
         "-- Do not edit by hand: run the tool again.", "local GL = GrudgeLedger", "GL.EngravingData = {", "    maps = {"]
for map_id in sorted(maps):
    lines.append("        [%d] = %s," % (map_id, lua(maps[map_id])))
lines += ["    },", "    names = {"]
for name in sorted(names):
    if name:
        lines.append("        [%s] = %s," % (lua(name), lua(names[name])))
lines += ["    },", "}", ""]
(WORK / "GrudgeLedger" / "EngravingData.lua").write_text("\n".join(lines), encoding="utf-8")
print(len(manifest["assets"]), "engravings,", len(maps), "maps,", len(names), "names")
